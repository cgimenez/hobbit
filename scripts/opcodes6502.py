"""Table des opcodes du 6502 NMOS (instructions documentées : 150).

Fournit la longueur de chaque opcode légal, l'ensemble des branchements,
et une routine de désassemblage linéaire qui comprend la convention
d'appel de The Hobbit : ``JSR $440D`` est suivi de 2 octets inline
(adresse du message à afficher), le code reprenant à JSR+5.
"""

from __future__ import annotations

